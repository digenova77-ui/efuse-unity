#!/usr/bin/env python3
"""geodns-agent — the GeoDNS actuator for the cluster balancer.

Reads the lane health snapshot, computes the routing table with
balancer.py, and rewrites the per-view answer files (answers.<view>).
Reloads BIND only when answers actually changed. Logs every change.

Rules (fail-safe, in order):
  1. A view answers its nearest healthy lane(s).
  2. A DOWN/UNKNOWN lane is removed from every view's answers.
  3. If NO lane is healthy: keep last-known-good answers (stale beats
     blackhole) and report DEGRADED. Never answer empty.
  4. Every answer change is logged with before/after; the balancer's
     collapse trace (via balancer.py --decide) is the permanent record.

Usage:
  geodns-agent.py --init <dir>          # assemble per-view zone files once
  geodns-agent.py --apply [--health PATH] [--zone-dir D] [--dry-run]
"""
import json
import os
import shutil
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import balancer
import health as healthmod

VIEWS = ["default", "europe", "apac", "mea", "oceania"]
ZONE_DIR = "/etc/bind"
HEALTH_PATH = "/var/lib/dualis/cluster/health.json"
CHANGELOG = "/var/lib/dualis/cluster/geodns-changes.jsonl"


def utcnow():
    from datetime import datetime, timezone
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def read_health(path):
    try:
        with open(path, "r", encoding="utf-8") as f:
            return json.load(f)
    except (OSError, ValueError):
        return {}


def render_answers(view, lanes):
    """Render the answer file body for a view's ordered healthy lanes."""
    lines = [
        "; answers.%s — GENERATED by geodns-agent.py %s. Do not hand-edit." % (view, utcnow()),
    ]
    if not lanes:
        lines.append("; DEGRADED: no healthy lane — last-known-good kept by operator")
        return "\n".join(lines) + "\n"
    for name in ("@", "www"):
        for lane in lanes:
            ip = balancer.LANES[lane]["ip"]
            lines.append("%-4s IN A %s" % (name, ip))
    return "\n".join(lines) + "\n"


def apply(zone_dir, health_path, dry_run=False):
    h = read_health(health_path)
    table = balancer.compute_table(h)
    changes = []
    for view in VIEWS:
        lanes = table.get(view, [])
        path = os.path.join(zone_dir, "answers." + view)
        if not lanes:
            # Rule 3: keep last-known-good; record DEGRADED.
            changes.append({"view": view, "action": "kept-last-known-good",
                            "reason": "no healthy lane", "at": utcnow()})
            continue
        new_body = render_answers(view, lanes)
        try:
            with open(path, "r", encoding="utf-8") as f:
                old_body = f.read()
        except OSError:
            old_body = None
        if old_body != new_body:
            changes.append({"view": view, "action": "rewrote",
                            "lanes": lanes, "at": utcnow()})
            if not dry_run:
                tmp = path + ".tmp"
                with open(tmp, "w", encoding="utf-8") as f:
                    f.write(new_body)
                os.replace(tmp, path)
    reloaded = False
    rndc_present = shutil.which("rndc") is not None
    if changes and not dry_run:
        wrote = [c for c in changes if c["action"] == "rewrote"]
        if wrote and rndc_present:
            r = subprocess.run(["rndc", "reload"], capture_output=True, text=True)
            reloaded = r.returncode == 0
            for c in wrote:
                c["rndc_reload"] = reloaded
        elif wrote:
            for c in wrote:
                c["rndc_reload"] = False
                c["rndc_note"] = "rndc not present — answers written, reload pending"
        os.makedirs(os.path.dirname(CHANGELOG), exist_ok=True)
        with open(CHANGELOG, "a", encoding="utf-8") as f:
            for c in changes:
                f.write(json.dumps(c, sort_keys=True) + "\n")
    return {"changes": changes, "reloaded": reloaded, "dry_run": dry_run}


def init(zone_dir):
    """Assemble per-view zone files from the base once."""
    src = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                       "db.dualiscapax.ai.base")
    with open(src, "r", encoding="utf-8") as f:
        base = f.read()
    for view in VIEWS:
        body = base.replace("$INCLUDE answers.base",
                            "$INCLUDE answers.%s ; view %s" % (view, view))
        dest = os.path.join(zone_dir, "db.dualiscapax.ai." + view)
        with open(dest, "w", encoding="utf-8") as f:
            f.write(body)
        print("wrote", dest)
    # copy the initial answer files too
    here = os.path.dirname(os.path.abspath(__file__))
    for view in VIEWS:
        s = os.path.join(here, "answers." + view)
        d = os.path.join(zone_dir, "answers." + view)
        if os.path.exists(s) and not os.path.exists(d):
            shutil.copy(s, d)
            print("installed", d)


def main(argv):
    import argparse
    p = argparse.ArgumentParser()
    p.add_argument("--init", metavar="ZONE_DIR")
    p.add_argument("--apply", action="store_true")
    p.add_argument("--health", default=HEALTH_PATH)
    p.add_argument("--zone-dir", default=ZONE_DIR)
    p.add_argument("--dry-run", action="store_true")
    ns = p.parse_args(argv)
    if ns.init:
        init(ns.init)
        return 0
    if ns.apply:
        print(json.dumps(apply(ns.zone_dir, ns.health, ns.dry_run),
                         indent=2, sort_keys=True))
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    main(sys.argv[1:])
